"use client";

import { useState, useEffect, useTransition, useRef } from "react";
import { generateSessionSummary } from "./actions";

type ReceiptSummaryProps = {
  sessionId: string;
  existingSummary: string | null;
  autoGenerate: boolean;
};

export function ReceiptSummary({
  sessionId,
  existingSummary,
  autoGenerate,
}: ReceiptSummaryProps) {
  const [summary, setSummary] = useState(existingSummary);
  const [generating, startGenerate] = useTransition();
  const hasAutoGenerated = useRef(false);

  useEffect(() => {
    if (autoGenerate && !hasAutoGenerated.current) {
      hasAutoGenerated.current = true;
      startGenerate(async () => {
        const result = await generateSessionSummary(sessionId);
        if ("summary" in result) {
          setSummary(result.summary);
        }
      });
    }
  }, [autoGenerate, sessionId]);

  function handleRegenerate() {
    startGenerate(async () => {
      const result = await generateSessionSummary(sessionId);
      if ("summary" in result) {
        setSummary(result.summary);
      }
    });
  }

  if (generating && !summary) {
    return (
      <div className="space-y-2.5">
        <div className="h-4 w-full animate-pulse rounded bg-muted" />
        <div className="h-4 w-5/6 animate-pulse rounded bg-muted" />
        <div className="h-4 w-4/6 animate-pulse rounded bg-muted" />
      </div>
    );
  }

  return (
    <>
      {summary && (
        <p className="text-sm leading-relaxed text-muted-foreground">
          {summary}
        </p>
      )}
      <button
        type="button"
        onClick={handleRegenerate}
        disabled={generating}
        className="mt-3 text-xs text-muted-foreground/60 transition-colors hover:text-muted-foreground disabled:opacity-50"
      >
        {generating ? "Regenerating..." : "Regenerate"}
      </button>
    </>
  );
}
